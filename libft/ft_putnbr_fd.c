#include "libft.h"

void	ft_putnbr_fd(int n, int fd)
{
	if (n < 0)
	{
		n = -n;
		ft_putchar_fd('-', fd);
	}
	else
	{
		ft_putnbr_fd(n / 10 + '0', fd);
		ft_putchar_fd(n % 10 + '0', fd);
		n /= 10;
	}
}